defmodule SketchWeb.ClientManifest do
  @moduledoc """
  Renders `assets/js/generated/manifest.ts` (ADR 0004): the element kinds and their specs, the
  style registry (ADR 0006), the toolbar tools, the export, history (ADR 0008) and zoom actions, the canvas
  geometry and the text whitespace, so the
  client never keeps its own copy of them.
  `mix sketch.gen.manifest` writes it and `mix sketch.gen.manifest --check` fails when it is stale.
  """

  alias SketchWeb.{ExportActions, HistoryActions, Tools, ZoomActions}

  @path "assets/js/generated/manifest.ts"

  @kind_spec_interface """
  export interface KindSpec {
    readonly id: ElementKind
    readonly geometry: "box" | { readonly points: { readonly min: number; readonly max: number } }
    readonly text: "none" | "optional" | "required"
    readonly drawGesture: "box" | "two_point" | "path" | "click_to_type"
    readonly defaultSize: { readonly width: number; readonly height: number }
    readonly style: readonly StyleProperty[]
  }
  """

  @tool_spec_interface """
  export interface ToolSpec {
    readonly id: string
    readonly label: string
    readonly keys: readonly string[]
    readonly creates: ElementKind | null
    readonly enabled: boolean
  }
  """

  @export_action_interface """
  export interface ExportChord {
    readonly code: string
    readonly mod: boolean
    readonly shift: boolean
    readonly alt: boolean
  }

  export interface ExportActionSpec {
    readonly id: string
    readonly label: string
    readonly chord: ExportChord | null
  }
  """

  @history_action_interface """
  export interface HistoryChord {
    readonly key: string
    readonly mod: "command" | "ctrl"
    readonly shift: boolean
  }

  export interface HistoryActionSpec {
    readonly id: string
    readonly label: string
    readonly chords: readonly HistoryChord[]
  }
  """

  @zoom_action_interface """
  export interface ZoomChord {
    readonly key: readonly string[]
    readonly code: string | null
    readonly mod: boolean
    readonly shift: boolean | null
  }

  export interface ZoomActionSpec {
    readonly id: string
    readonly label: string
    readonly chords: readonly ZoomChord[]
  }
  """

  @spec path() :: Path.t()
  def path, do: @path

  @spec render() :: String.t()
  def render do
    specs = Sketch.Canvas.kind_specs()

    [
      "// Generated by `mix sketch.gen.manifest` from Sketch.Canvas.Kinds, Sketch.Canvas.Style, SketchWeb.Tools, SketchWeb.ExportActions, SketchWeb.HistoryActions, SketchWeb.ZoomActions and Sketch.Canvas.Geometry. Do not edit.\n",
      literal_list("ELEMENT_KINDS", "ElementKind", Sketch.Canvas.element_kinds()),
      literal_list("STYLE_PROPERTIES", "StyleProperty", Sketch.Canvas.style_properties()),
      style_tokens(),
      stroke_widths(),
      dash_arrays(),
      @kind_spec_interface,
      record(
        "KIND_SPECS",
        "Record<ElementKind, KindSpec>",
        Enum.map(specs, &{&1.id, kind_spec(&1)})
      ),
      literal_list("POINT_KINDS", "PointKind", Sketch.Canvas.point_kinds()),
      literal_list(
        "TEXT_KINDS",
        "TextKind",
        for(%{id: id, text: text} <- specs, text != :none, do: id)
      ),
      literal_list(
        "REQUIRED_TEXT_KINDS",
        "RequiredTextKind",
        for(%{id: id, text: :required} <- specs, do: id)
      ),
      literal_list(
        "TYPED_KINDS",
        "TypedKind",
        for(%{id: id, draw_gesture: :click_to_type} <- specs, do: id)
      ),
      @tool_spec_interface,
      tools(),
      "export type ToolId = (typeof TOOLS)[number][\"id\"]\n",
      "export const DEFAULT_TOOL: ToolId = #{string(Tools.default_id())}\n",
      @export_action_interface,
      export_actions(),
      "export type ExportActionId = (typeof EXPORT_ACTIONS)[number][\"id\"]\n",
      @history_action_interface,
      history_actions(),
      "export type HistoryActionId = (typeof HISTORY_ACTIONS)[number][\"id\"]\n",
      @zoom_action_interface,
      zoom_actions(),
      "export type ZoomActionId = (typeof ZOOM_ACTIONS)[number][\"id\"]\n",
      geometry(),
      "export const TEXT_WHITESPACE: readonly string[] = [#{Enum.map_join(Sketch.Canvas.text_whitespace(), ", ", &string/1)}]\n"
    ]
    |> Enum.join("\n")
  end

  defp literal_list(name, type, values) do
    """
    export const #{name} = [#{Enum.map_join(values, ", ", &string/1)}] as const

    export type #{type} = (typeof #{name})[number]
    """
  end

  defp record(name, type, entries) do
    lines = Enum.map_join(entries, "", fn {key, value} -> "  #{key}: #{value},\n" end)
    "export const #{name} = {\n#{lines}} as const satisfies #{type}\n"
  end

  defp kind_spec(spec) do
    object(
      id: string(spec.id),
      geometry: geometry_spec(spec.geometry),
      text: string(spec.text),
      drawGesture: string(spec.draw_gesture),
      defaultSize: object(width: spec.default_size.width, height: spec.default_size.height),
      style: "[#{Enum.map_join(spec.style, ", ", &string/1)}]"
    )
  end

  defp style_tokens do
    entries =
      Enum.map(Sketch.Canvas.style_properties(), fn property ->
        {property, "[#{Enum.map_join(Sketch.Canvas.style_tokens(property), ", ", &string/1)}]"}
      end)

    [
      "export const STYLE_TOKENS = {\n",
      Enum.map_join(entries, "", fn {key, value} -> "  #{key}: #{value},\n" end),
      "} as const satisfies Record<StyleProperty, readonly string[]>\n\n",
      "export type StyleToken<P extends StyleProperty> = (typeof STYLE_TOKENS)[P][number]\n"
    ]
    |> IO.iodata_to_binary()
  end

  defp stroke_widths do
    record(
      "STROKE_WIDTHS",
      "Record<StyleToken<\"stroke_width\">, { readonly stroke: number; readonly sketch: string }>",
      Enum.map(Sketch.Canvas.style_tokens(:stroke_width), fn width ->
        {width,
         object(
           stroke: Sketch.Canvas.style_stroke_px(width),
           sketch: string(Sketch.Canvas.style_sketch_px(width))
         )}
      end)
    )
  end

  defp dash_arrays do
    widths = Sketch.Canvas.style_tokens(:stroke_width)

    record(
      "DASH_ARRAYS",
      "Record<StyleToken<\"stroke_style\">, Record<StyleToken<\"stroke_width\">, string | null>>",
      Enum.map(Sketch.Canvas.style_tokens(:stroke_style), fn style ->
        {style,
         object(
           Enum.map(widths, fn width ->
             {width, dash_array(Sketch.Canvas.style_dash_array(style, width))}
           end)
         )}
      end)
    )
  end

  defp dash_array(nil), do: "null"
  defp dash_array(dash_array), do: string(dash_array)

  defp geometry_spec(:box), do: string(:box)

  defp geometry_spec({:points, range}),
    do: object(points: object(min: range.first, max: range.last))

  defp tools do
    lines =
      Enum.map_join(Tools.all(), "", fn tool ->
        fields = [
          id: string(tool.id),
          label: string(tool.label),
          keys: "[#{Enum.map_join(tool.keys, ", ", &string/1)}]",
          creates: if(tool.creates, do: string(tool.creates), else: "null"),
          enabled: to_string(tool.enabled)
        ]

        "  #{object(fields)},\n"
      end)

    "export const TOOLS = [\n#{lines}] as const satisfies readonly ToolSpec[]\n"
  end

  defp export_actions do
    lines =
      Enum.map_join(ExportActions.all(), "", fn action ->
        fields = [id: string(action.id), label: string(action.label), chord: chord(action.chord)]
        "  #{object(fields)},\n"
      end)

    "export const EXPORT_ACTIONS = [\n#{lines}] as const satisfies readonly ExportActionSpec[]\n"
  end

  defp history_actions do
    lines =
      Enum.map_join(HistoryActions.all(), "", fn action ->
        chords =
          Enum.map_join(action.chords, ", ", fn chord ->
            object(key: string(chord.key), mod: string(chord.mod), shift: chord.shift)
          end)

        "  #{object(id: string(action.id), label: string(action.label), chords: "[#{chords}]")},\n"
      end)

    "export const HISTORY_ACTIONS = [\n#{lines}] as const satisfies readonly HistoryActionSpec[]\n"
  end

  defp zoom_actions do
    lines =
      Enum.map_join(ZoomActions.all(), "", fn action ->
        chords =
          Enum.map_join(action.chords, ", ", fn chord ->
            object(
              key: "[#{Enum.map_join(chord.key, ", ", &string/1)}]",
              code: nullable_string(chord.code),
              mod: chord.mod,
              shift: if(is_nil(chord.shift), do: "null", else: chord.shift)
            )
          end)

        "  #{object(id: string(action.id), label: string(action.label), chords: "[#{chords}]")},\n"
      end)

    "export const ZOOM_ACTIONS = [\n#{lines}] as const satisfies readonly ZoomActionSpec[]\n"
  end

  defp nullable_string(nil), do: "null"
  defp nullable_string(value), do: string(value)

  defp chord(nil), do: "null"

  defp chord(chord),
    do: object(code: string(chord.code), mod: chord.mod, shift: chord.shift, alt: chord.alt)

  defp geometry do
    lines =
      Sketch.Canvas.geometry()
      |> Enum.sort()
      |> Enum.map_join("", fn {key, value} -> "  #{camel_case(key)}: #{value},\n" end)

    "export const GEOMETRY = {\n#{lines}} as const\n"
  end

  defp object(fields),
    do: "{ #{Enum.map_join(fields, ", ", fn {key, value} -> "#{key}: #{value}" end)} }"

  defp string(value), do: value |> to_string() |> JSON.encode!()

  defp camel_case(key) do
    [first | rest] = key |> Atom.to_string() |> String.split("_")
    Enum.join([first | Enum.map(rest, &String.capitalize/1)])
  end
end
