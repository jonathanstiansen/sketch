defmodule SketchWeb.ClientManifest do
  @moduledoc """
  Renders `assets/js/generated/manifest.ts` (ADR 0004): the element kinds and their specs, the
  style registry (ADR 0006), the toolbar tools, the export, history (ADR 0008) and zoom actions, the
  keyboard shortcuts and pointer gestures of all of them from `SketchWeb.Shortcuts` (A23), the
  payload of every event a client may push from `SketchWeb.BoardEvents`, the canvas geometry and
  the text whitespace, so the client never keeps its own copy of them.
  `mix sketch.gen.manifest` writes it and `mix sketch.gen.manifest --check` fails when it is stale.
  """

  alias SketchWeb.{
    BoardEvents,
    ClipboardActions,
    ExportActions,
    HistoryActions,
    Shortcuts,
    Tools,
    ZoomActions
  }

  @path "assets/js/generated/manifest.ts"

  @kind_spec_interface """
  export interface KindSpec {
    readonly id: ElementKind
    readonly geometry: "box" | { readonly points: { readonly min: number; readonly max: number } }
    readonly text: "none" | "optional" | "required"
    readonly drawGesture: "box" | "two_point" | "path" | "click_to_type"
    readonly defaultSize: { readonly width: number; readonly height: number }
    readonly style: readonly StyleProperty[]
  }
  """

  @tool_spec_interface """
  export interface ToolSpec {
    readonly id: string
    readonly label: string
    readonly creates: ElementKind | null
    readonly enabled: boolean
  }
  """

  @action_interface """
  export interface ActionSpec {
    readonly id: string
    readonly label: string
  }
  """

  @shortcut_interface """
  export interface ShortcutChord {
    readonly key: readonly string[]
    readonly code: string | null
    readonly mod: "none" | "command" | "ctrl"
    readonly shift: boolean | null
    readonly alt: boolean
    readonly modifiers: "exact" | "ignore_alt" | "any"
  }

  export interface ShortcutSpec {
    readonly group: ShortcutGroup
    readonly action: string
    readonly contexts: readonly FocusContext[]
    readonly chords: readonly ShortcutChord[]
  }
  """

  @pointer_gesture_interface """
  export interface PointerGestureSpec {
    readonly action: string
    readonly button: "primary" | "middle" | "wheel"
    readonly tools: readonly ToolId[]
    readonly target: "element" | "empty" | "handle" | null
    readonly space: boolean | null
    readonly shift: boolean | null
    readonly alt: boolean | null
    readonly mod: "command" | null
  }
  """

  @spec path() :: Path.t()
  def path, do: @path

  @spec render() :: String.t()
  def render do
    specs = Sketch.Canvas.kind_specs()

    [
      "// Generated by `mix sketch.gen.manifest` from the registries SketchWeb.ClientManifest reads. Do not edit.\n",
      literal_list("ELEMENT_KINDS", "ElementKind", Sketch.Canvas.element_kinds()),
      literal_list("STYLE_PROPERTIES", "StyleProperty", Sketch.Canvas.style_properties()),
      style_tokens(),
      stroke_widths(),
      dash_arrays(),
      @kind_spec_interface,
      record(
        "KIND_SPECS",
        "Record<ElementKind, KindSpec>",
        Enum.map(specs, &{&1.id, kind_spec(&1)})
      ),
      literal_list("POINT_KINDS", "PointKind", Sketch.Canvas.point_kinds()),
      literal_list(
        "TEXT_KINDS",
        "TextKind",
        for(%{id: id, text: text} <- specs, text != :none, do: id)
      ),
      literal_list(
        "REQUIRED_TEXT_KINDS",
        "RequiredTextKind",
        for(%{id: id, text: :required} <- specs, do: id)
      ),
      literal_list(
        "TYPED_KINDS",
        "TypedKind",
        for(%{id: id, draw_gesture: :click_to_type} <- specs, do: id)
      ),
      @tool_spec_interface,
      tools(),
      "export type ToolId = (typeof TOOLS)[number][\"id\"]\n",
      "export const DEFAULT_TOOL: ToolId = #{string(Tools.default_id())}\n",
      @action_interface,
      actions("EXPORT_ACTIONS", ExportActions.all()),
      "export type ExportActionId = (typeof EXPORT_ACTIONS)[number][\"id\"]\n",
      actions("HISTORY_ACTIONS", HistoryActions.all()),
      "export type HistoryActionId = (typeof HISTORY_ACTIONS)[number][\"id\"]\n",
      actions("CLIPBOARD_ACTIONS", ClipboardActions.all()),
      "export type ClipboardActionId = (typeof CLIPBOARD_ACTIONS)[number][\"id\"]\n",
      actions("ZOOM_ACTIONS", ZoomActions.all()),
      "export type ZoomActionId = (typeof ZOOM_ACTIONS)[number][\"id\"]\n",
      literal_list("FOCUS_CONTEXTS", "FocusContext", Enum.map(Shortcuts.contexts(), & &1.id)),
      context_overlaps(),
      literal_list("SHORTCUT_GROUPS", "ShortcutGroup", Shortcuts.groups()),
      @shortcut_interface,
      shortcuts(),
      "export type Shortcut = (typeof SHORTCUTS)[number]\n",
      "export type ShortcutAction = Shortcut[\"action\"]\n",
      @pointer_gesture_interface,
      pointer_gestures(),
      client_events(),
      geometry(),
      "export const TEXT_WHITESPACE: readonly string[] = [#{Enum.map_join(Sketch.Canvas.text_whitespace(), ", ", &string/1)}]\n"
    ]
    |> Enum.join("\n")
  end

  defp literal_list(name, type, values) do
    """
    export const #{name} = [#{Enum.map_join(values, ", ", &string/1)}] as const

    export type #{type} = (typeof #{name})[number]
    """
  end

  defp record(name, type, entries) do
    lines = Enum.map_join(entries, "", fn {key, value} -> "  #{key}: #{value},\n" end)
    "export const #{name} = {\n#{lines}} as const satisfies #{type}\n"
  end

  defp kind_spec(spec) do
    object(
      id: string(spec.id),
      geometry: geometry_spec(spec.geometry),
      text: string(spec.text),
      drawGesture: string(spec.draw_gesture),
      defaultSize: object(width: spec.default_size.width, height: spec.default_size.height),
      style: "[#{Enum.map_join(spec.style, ", ", &string/1)}]"
    )
  end

  defp style_tokens do
    entries =
      Enum.map(Sketch.Canvas.style_properties(), fn property ->
        {property, "[#{Enum.map_join(Sketch.Canvas.style_tokens(property), ", ", &string/1)}]"}
      end)

    [
      "export const STYLE_TOKENS = {\n",
      Enum.map_join(entries, "", fn {key, value} -> "  #{key}: #{value},\n" end),
      "} as const satisfies Record<StyleProperty, readonly string[]>\n\n",
      "export type StyleToken<P extends StyleProperty> = (typeof STYLE_TOKENS)[P][number]\n\n",
      "export const STYLE_DEFAULTS: { readonly [P in StyleProperty]: StyleToken<P> } = {\n",
      Enum.map_join(Sketch.Canvas.style_properties(), "", fn property ->
        "  #{property}: #{string(Map.fetch!(Sketch.Canvas.style_defaults(), property))},\n"
      end),
      "}\n"
    ]
    |> IO.iodata_to_binary()
  end

  defp stroke_widths do
    record(
      "STROKE_WIDTHS",
      "Record<StyleToken<\"stroke_width\">, { readonly stroke: number; readonly sketch: string }>",
      Enum.map(Sketch.Canvas.style_tokens(:stroke_width), fn width ->
        {width,
         object(
           stroke: Sketch.Canvas.style_stroke_px(width),
           sketch: string(Sketch.Canvas.style_sketch_px(width))
         )}
      end)
    )
  end

  defp dash_arrays do
    widths = Sketch.Canvas.style_tokens(:stroke_width)

    record(
      "DASH_ARRAYS",
      "Record<StyleToken<\"stroke_style\">, Record<StyleToken<\"stroke_width\">, string | null>>",
      Enum.map(Sketch.Canvas.style_tokens(:stroke_style), fn style ->
        {style,
         object(
           Enum.map(widths, fn width ->
             {width, dash_array(Sketch.Canvas.style_dash_array(style, width))}
           end)
         )}
      end)
    )
  end

  defp dash_array(nil), do: "null"
  defp dash_array(dash_array), do: string(dash_array)

  defp geometry_spec(:box), do: string(:box)

  defp geometry_spec({:points, range}),
    do: object(points: object(min: range.first, max: range.last))

  defp tools do
    lines =
      Enum.map_join(Tools.all(), "", fn tool ->
        fields = [
          id: string(tool.id),
          label: string(tool.label),
          creates: if(tool.creates, do: string(tool.creates), else: "null"),
          enabled: to_string(tool.enabled)
        ]

        "  #{object(fields)},\n"
      end)

    "export const TOOLS = [\n#{lines}] as const satisfies readonly ToolSpec[]\n"
  end

  defp actions(name, actions) do
    lines =
      Enum.map_join(actions, "", fn action ->
        "  #{object(id: string(action.id), label: string(action.label))},\n"
      end)

    "export const #{name} = [\n#{lines}] as const satisfies readonly ActionSpec[]\n"
  end

  defp shortcuts do
    lines =
      Enum.map_join(Shortcuts.keyboard(), "", fn shortcut ->
        fields = [
          group: string(shortcut.group),
          action: string(shortcut.action),
          contexts: "[#{Enum.map_join(shortcut.contexts, ", ", &string/1)}]",
          chords: "[#{Enum.map_join(shortcut.chords, ", ", &chord/1)}]"
        ]

        "  #{object(fields)},\n"
      end)

    "export const SHORTCUTS = [\n#{lines}] as const satisfies readonly ShortcutSpec[]\n"
  end

  defp pointer_gestures do
    lines =
      Enum.map_join(Shortcuts.pointer_gestures(), "", fn gesture ->
        fields = [
          action: string(gesture.action),
          button: string(gesture.button),
          tools: "[#{Enum.map_join(gesture.tools, ", ", &string/1)}]",
          target: any_or_string(gesture.target),
          space: any_or_boolean(gesture.space),
          shift: any_or_boolean(gesture.shift),
          alt: any_or_boolean(gesture.alt),
          mod: any_or_string(gesture.mod)
        ]

        "  #{object(fields)},\n"
      end)

    "export const POINTER_GESTURES = [\n#{lines}] as const satisfies readonly PointerGestureSpec[]\n"
  end

  defp any_or_string(:any), do: "null"
  defp any_or_string(value), do: string(value)

  defp any_or_boolean(:any), do: "null"
  defp any_or_boolean(value), do: to_string(value)

  defp client_events do
    lines =
      Enum.map_join(BoardEvents.all(), "", fn event ->
        "  readonly #{string(event.event)}: #{payload_type(event.payload)}\n"
      end)

    """
    export interface ClientEventPayloads {
    #{lines}}

    export type ClientEventName = keyof ClientEventPayloads
    """
  end

  defp payload_type(payload) when map_size(payload) == 0, do: "Record<string, never>"

  defp payload_type(payload) do
    fields =
      payload
      |> Enum.sort()
      |> Enum.map_join("; ", fn
        {field, {:optional, type}} -> "readonly #{field}?: #{field_type(type)}"
        {field, type} -> "readonly #{field}: #{field_type(type)}"
      end)

    "{ #{fields} }"
  end

  defp field_type(:integer), do: "number"
  defp field_type(:string), do: "string"
  defp field_type(:kind), do: "ElementKind"
  defp field_type(:points), do: "readonly { readonly x: number; readonly y: number }[]"
  defp field_type({:style_token, property}), do: "StyleToken<#{string(property)}>"
  defp field_type({:list, type}), do: "readonly #{field_type(type)}[]"
  defp field_type(payload) when is_map(payload), do: payload_type(payload)

  defp context_overlaps do
    pairs =
      for context <- Shortcuts.contexts(), other <- context.overlaps do
        "[#{string(context.id)}, #{string(other)}]"
      end

    "export const CONTEXT_OVERLAPS: readonly (readonly [FocusContext, FocusContext])[] = [#{Enum.join(pairs, ", ")}]\n"
  end

  defp chord(chord) do
    object(
      key: "[#{Enum.map_join(chord.key, ", ", &string/1)}]",
      code: nullable_string(chord.code),
      mod: string(chord.mod),
      shift: if(chord.shift == :any, do: "null", else: chord.shift),
      alt: chord.alt,
      modifiers: string(chord.modifiers)
    )
  end

  defp nullable_string(nil), do: "null"
  defp nullable_string(value), do: string(value)

  defp geometry do
    lines =
      Sketch.Canvas.geometry()
      |> Enum.sort()
      |> Enum.map_join("", fn {key, value} -> "  #{camel_case(key)}: #{value},\n" end)

    "export const GEOMETRY = {\n#{lines}} as const\n"
  end

  defp object(fields),
    do: "{ #{Enum.map_join(fields, ", ", fn {key, value} -> "#{key}: #{value}" end)} }"

  defp string(value), do: value |> to_string() |> JSON.encode!()

  defp camel_case(key) do
    [first | rest] = key |> Atom.to_string() |> String.split("_")
    Enum.join([first | Enum.map(rest, &String.capitalize/1)])
  end
end
